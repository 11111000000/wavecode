import { type JSX } from 'solid-js';
import { MicIcon } from '../icons';
import { openInputSheet, getInputMode, isInputSheetOpen } from '../state/inputMode';
import { INPUT_MODE_LABEL } from '../state/labels';

/**
 * InputFAB — единственная плавающая кнопка приложения.
 *
 * Одно нажатие — одно значение
 * ----------------------------
 * Кнопка открывает лист ввода. Всегда. Она никогда не начинает запись
 * сама и никогда не меняет смысл в зависимости от скрытого состояния.
 *
 * Раньше кнопка вела себя по-разному: в режиме голоса она была REC,
 * в режиме ритма — тап-падом, и подпись молча менялась с «Голос» на
 * «Ритм». Режим жил во внутреннем сторе, переключатель — в доке, до
 * которого надо было ещё добраться. Пользователь не мог заранее знать,
 * что получит, нажав кнопку. Это и было источником ощущения «я сейчас
 * голос записываю мелодию или там ритм».
 *
 * Теперь всё, что кнопка может сделать, — открыть лист ввода, где
 * модальность выбирается явной вкладкой «Речь | Свист | Ритм» и
 * подсвечена прямо на экране.
 *
 * Что было у removed-кластера
 * --------------------------
 * Раньше в правом нижнем углу стояли две кнопки: «Голос» и «Свист»,
 * одна над другой. Обе открывали микрофон, а вторая делала ровно то
 * же, что и лист «Микрофон». Две кнопки, одно устройство, два способа
 * сказать одно и то же. Кластер ушёл, осталась одна кнопка.
 *
 * Про speed-dial, который уже пробовали
 * -------------------------------------
 * Большая кнопка, раскрывающаяся в стопку кнопок, была отвергнута:
 * «жму микрофон — открывается ещё одна кнопка с микрофоном, непонятно
 * что вообще происходит». Лист с вкладками — не то же самое: там
 * сразу видно, сколько вариантов и какой выбран.
 */
export function InputFAB(): JSX.Element {
  const title = (): string =>
    `Ввод — сейчас ${INPUT_MODE_LABEL[getInputMode()]}`;

  return (
    <div class="voice-fab-group">
      <div class="voice-mini-fab-stack">
        <button
          type="button"
          class="voice-mini-fab voice-mini-fab--ai voice-mini-fab--input"
          data-mode="input"
          data-state={isInputSheetOpen() ? 'open' : 'idle'}
          aria-haspopup="dialog"
          aria-label="Ввод"
          title={title()}
          onClick={() => { openInputSheet(); }}
        >
          <MicIcon size={18} />
          <span class="voice-mini-fab__label" aria-hidden="true">
            Ввод
          </span>
        </button>
      </div>
    </div>
  );
}
